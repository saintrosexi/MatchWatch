export const COLD_START_IDS = Object.freeze(COLD_START_TITLES.map((t) => t.id));

/** Быстрая проверка принадлежности: вызывается на каждый тайтл при ранжировании. */
const ID_SET = new Set(COLD_START_IDS);

export const isColdStartTitle = (title) =>
  Boolean(title) && ID_SET.has(Number(title.externalId ?? title.id));
