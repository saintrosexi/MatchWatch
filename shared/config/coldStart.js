/**
 * Стартовый набор.
 *
 * До первых свайпов профиль вкуса пуст, и порядок ленты определяется
 * одним лишь качеством фильма — то есть выходит одинаковым у всех.
 * Набор решает не эту косметику, а задачу под ней: пятнадцать карточек
 * должны развести человека по осям, а не показать пятнадцать раз одно
 * и то же. Поэтому подбор идёт не по любимости, а по непохожести:
 * рядом стоят космическая драма и комедия про похмелье, аниме и хоррор.
 *
 * Узнаваемость обязательна. О фильме, которого человек не видел и
 * не слышал, он не может сказать ничего, кроме «не знаю» — а такой ответ
 * профиль не двигает.
 *
 * Список намеренно короткий и правится руками: это редакторское решение,
 * а не выборка. Проверять его стоит раз в год — состав «того, что видели
 * все» медленно, но меняется.
 */

