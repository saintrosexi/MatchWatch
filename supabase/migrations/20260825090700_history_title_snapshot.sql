-- MatchWatch: снимок карточки в истории реакций.
--
-- Раньше история хранила только факт («посмотрено», «не понравилось»),
-- и показать список просмотренного было не из чего: постер и название
-- пришлось бы каждый раз доставать из каталога отдельным запросом.
-- Компактный снимок решает это одной колонкой.

alter table public.title_history
  add column if not exists title jsonb;

comment on column public.title_history.title is
  'Компактная карточка (id, название, год, постер, рейтинг) на момент реакции. '
  'Нужна, чтобы «Просмотрено» и «Не понравилось» рисовались без обращения к каталогу.';

-- Выборка «что я посмотрел» — частый запрос вкладки «Коллекция».
create index if not exists title_history_action_idx
  on public.title_history (user_id, action, updated_at desc);
