-- MatchWatch: автопилот разметки — задача в расписании базы.
--
-- Разметка встала 27 августа и три дня не двигалась, а вместе с ней
-- встало и качество ленты: треть каталога осталась с тремя тегами,
-- то есть практически с одними жанрами. Косинусная близость по трём
-- жанрам совпадает у сотен фильмов, и на этой трети подбор по вкусу
-- переставал отличаться от случайного — что и показали метрики:
-- 24% принятия в слоте «похожее на любимое» против 26% в разведке.
--
-- Причина оказалась одной строкой. Всё остальное было на месте:
-- функция ops.sweep_markup() существует, адрес и секрет для вызова
-- пишет эндпоинт /api/ops/markup-cron, разметка через pg_net работает.
-- Не хватало записи в cron.job — звать функцию раз в четверть часа
-- было некому.
--
-- Пятнадцать минут по шесть фильмов — около шестисот в сутки, столько
-- выдерживают два ключа Gemini. Очередь конечна: догнав каталог,
-- автопилот работает вхолостую и квоту почти не тратит.
select cron.schedule('markup-sweep', '*/15 * * * *', 'select ops.sweep_markup();');
